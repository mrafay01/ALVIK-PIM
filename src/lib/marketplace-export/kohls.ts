// numeric-coded taxonomy columns after these are intentionally left blank.
export function mapItemToKohlsRow(fields: ResolvedListingFields): Record<string, string | number> {
  const bullets = fields.bulletFeatures;
  const featureFields: Record<string, string> = {};
  for (let i = 1; i <= 20; i++) {
    featureFields[`feature_${i}`] = bullets[i - 1] ?? "";
  }

  return {
    product_category: fields.marketplaceCategory,
    upc_number: fields.upc,
    uid_code: fields.gtin,
    title: fields.productTitle,
    brand: "",
    meta_description: fields.productDescription,
    style_number: fields.itemNumber,
    style_description: fields.productTitle,
    display_color: "",
    color_family: "",
    main_image: "",
    alt_image_1: "",
    alt_image_2: "",
    alt_image_3: "",
    alt_image_4: "",
    care: fields.careInstructions,
    ...featureFields,
    fabric_material: fields.metal,
    origin: fields.countryOfOrigin,
    choking_hazard: fields.chokingHazardWarning,
    perishable_indicator: "",
    prop_65: fields.prop65Warning,
    is_ltl_item: "",
    Priority: "",
    containsPFAS: "",
    ai_decision: "",
    ai_confidence_pct: "",
    ai_comment: "",
  };
}
