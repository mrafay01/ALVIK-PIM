    "onboarding-in-progress": "",
    gemrulesetflag: "",
    isCABatteryFeeEligible: "",
    "taxCode-watches&jewelry": "",
    "fnb20-1": fields.gender,
    Hazmat: "",
    "Hazmat Battery Test Sheet": "",
